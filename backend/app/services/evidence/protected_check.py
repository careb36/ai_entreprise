"""The Verifier's ``protected_paths`` check (``docs/design/rsi-loop.md``,
section 3.3, layer 1; REQ-10).

For a company that hosts the factory (``companies.protected_paths_enabled``,
``services/platform/protected_paths_setting.py``), the paths a delivery
changed are matched against the protected list
(``services/contracts/protected_paths.py``): the graders, the evidence, CI,
the rules and the list itself. The paths are the ones the platform observed:
the daemon's report of what it wrote and read back (``workspace_writes``,
status ``written``) and the files the daemon saw a console producer change
(``console_run.files``). The paths the producer declared are added: a claim
may add to a match, never remove one.

The list in force is the running backend's, shipped with its code:
``protected_list.json`` beside this module, generated by
``scripts/protected_paths_data.py`` from the tuple in contracts and the tests
whose contexts include ``evidence`` in the test map
(``docs/architecture/contexts.json``, which the backend image does not have);
``tests/test_protected_paths_review.py`` keeps it in step with the map. It is
never read from the company's project, which is what the sprint's agents can
write. If the file cannot be read, the guard fails closed
(``ProtectedListUnavailable``): the check is ``unverifiable``, the tier
``high``, and no rule or reviewer closes the task without a person.

A match is a reason for a person, not a fault: the check's outcome is
``pass`` with the matched paths in the observation and in ``matches``, and
the ``risk_tier`` check rises to ``high`` with the area ``grader``
(``risk.classify``), so the task waits for a person at every autonomy level
and no Manager rule accepts it (``manager_rules._accept_high_risk``).
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Sequence
from functools import lru_cache
from pathlib import Path
from typing import Any

from services.contracts import protected_paths
from services.evidence import claimed_paths

CHECK_NAME = "protected_paths"
DATA_FILE = Path(__file__).resolve().with_name("protected_list.json")
UNAVAILABLE = "the protected-path list could not be read"
_QUOTED = 20


class ProtectedListUnavailable(RuntimeError):
    """The shipped list is missing or malformed: hold, never pass."""


@lru_cache(maxsize=1)
def patterns_in_force() -> tuple[str, ...]:
    """The list the running backend ships; ``ProtectedListUnavailable`` without it."""
    try:
        patterns = json.loads(DATA_FILE.read_text(encoding="utf-8"))["patterns"]
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise ProtectedListUnavailable(f"{UNAVAILABLE}: {exc}") from exc
    if not isinstance(patterns, list) or not all(
        isinstance(p, str) and p for p in patterns
    ):
        raise ProtectedListUnavailable(f"{UNAVAILABLE}: malformed")
    # The tuple in contracts always holds, whatever the file says.
    extra = [p for p in patterns if p not in protected_paths.PATTERNS]
    return protected_paths.PATTERNS + tuple(dict.fromkeys(extra))


def unavailable(reason: str) -> dict[str, Any]:
    """The check when the list cannot be read: unverifiable, so the task waits."""
    return {
        "name": CHECK_NAME,
        "outcome": "unverifiable",
        "observation": f"{reason}; a person decides",
        "matches": [],
        "observed": False,
        "patterns": 0,
    }


def _strings(values: Iterable[Any]) -> list[str]:
    return [v for v in values if isinstance(v, str) and v]


def observed_paths(evidence: dict[str, Any] | None) -> list[str] | None:
    """The paths the daemon saw change, or ``None`` when it reported none at all."""
    evidence = evidence or {}
    writes = evidence.get("workspace_writes")
    console = evidence.get("console_run")
    if not isinstance(writes, list) and not isinstance(console, dict):
        return None
    paths: list[str] = []
    if isinstance(writes, list):
        paths += _strings(
            w.get("path")
            for w in writes
            if isinstance(w, dict) and w.get("status") == "written"
        )
    if isinstance(console, dict):
        paths += _strings(
            f.get("path") for f in console.get("files") or [] if isinstance(f, dict)
        )
    return paths


def check(
    evidence: dict[str, Any] | None,
    declared: Iterable[Any],
    patterns: Sequence[str],
) -> dict[str, Any]:
    """The protected paths a delivery touched, from what was observed and declared."""
    observed = observed_paths(evidence)
    seen = set(observed or [])
    found = protected_paths.matches([*(observed or []), *_strings(declared)], patterns)
    matched = [
        {
            "path": m.path,
            "pattern": m.pattern,
            "observed": any(protected_paths.normalize(p) == m.path for p in seen),
        }
        for m in found
    ]
    if matched:
        shown = ", ".join(f"{m['path']} ({m['pattern']})" for m in matched[:_QUOTED])
        more = f" (and {len(matched) - _QUOTED} more)" if len(matched) > _QUOTED else ""
        observation = f"protected paths touched, a person decides: {shown}{more}"
    else:
        declared_count = len(_strings(declared))
        observation = (
            f"no protected path among {len(seen)} observed and "
            f"{declared_count} declared path(s)"
        )
    if observed is None:
        observation += "; the daemon reported no writes"
    return {
        "name": CHECK_NAME,
        "outcome": "pass",
        "observation": observation,
        "matches": matched,
        "observed": observed is not None,
        "patterns": len(patterns),
    }


def touched(
    claims: dict[str, Any] | None,
    subject: dict[str, Any] | None,
    recorded: dict[str, Any] | None,
) -> list[str]:
    """The protected paths a recorded run touched, matched again now.

    For a decision taken after the delivery (a flag turned on since): the
    matches the Verifier recorded (*recorded* is the verification as
    ``{"checks", "evidence"}``), plus the run's paths matched against the list
    in force, from the same sources as at delivery (the daemon's observations
    and ``claimed_paths.declared_paths``) and ``subject.changed_files``.
    Raises ``ProtectedListUnavailable`` without the list: the caller holds.
    """
    recorded = recorded or {}
    evidence = recorded.get("evidence") or {}
    paths = [
        *(observed_paths(evidence) or []),
        *_strings((subject or {}).get("changed_files") or []),
        *claimed_paths.declared_paths(claims, evidence),
    ]
    found = [m.path for m in protected_paths.matches(paths, patterns_in_force())]
    earlier = [
        str(m.get("path"))
        for c in recorded.get("checks") or []
        if isinstance(c, dict) and c.get("name") == CHECK_NAME
        for m in c.get("matches") or []
        if isinstance(m, dict) and m.get("path")
    ]
    return list(dict.fromkeys([*earlier, *found]))
