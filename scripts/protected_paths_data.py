#!/usr/bin/env python3
"""Write the protected-path list the backend ships
(``backend/app/services/evidence/protected_list.json``).

The backend image is built from ``backend/`` alone, so it has no
``docs/architecture/contexts.json``. The list in force (the tuple in
``services/contracts/protected_paths.py`` plus the tests whose contexts include
``evidence`` in that test map) is therefore generated here as runtime data.
``backend/tests/test_protected_paths_review.py`` fails when the file and the
map disagree; run this script and commit the result, which is itself a
protected path (a person reviews it).

Usage: python3 scripts/protected_paths_data.py [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TEST_MAP = REPO / "docs/architecture/contexts.json"
OUT = REPO / "backend/app/services/evidence/protected_list.json"

sys.path.insert(0, str(REPO / "backend/app"))
from services.contracts import protected_paths  # noqa: E402


def render() -> str:
    test_map = json.loads(TEST_MAP.read_text(encoding="utf-8"))["tests"]["files"]
    data = {
        "$comment": (
            "Generated by scripts/protected_paths_data.py from "
            "services/contracts/protected_paths.py and the test map in "
            "docs/architecture/contexts.json; do not edit by hand."
        ),
        "patterns": list(protected_paths.protected_patterns(test_map)),
    }
    return json.dumps(data, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run {Path(__file__).name}")
            return 1
        print(f"{OUT.relative_to(REPO)} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
