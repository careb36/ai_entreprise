import ast
import subprocess
import tempfile
import os
from typing import TypedDict, List, Dict, Any, Optional
from pydantic import BaseModel, Field

class Artifact(BaseModel):
    """
    Represents a code artifact generated by an autonomous agent.
    Strictly separates agent claims from system observations (STD-AUD-1).
    """
    id: str
    language: str  # e.g., 'python', 'typescript'
    content: str
    
    # What the agent says it did
    claims: Dict[str, Any] = Field(default_factory=dict)
    
    # What the daemon, tests, and checks saw
    observations: Dict[str, Any] = Field(default_factory=dict)


class GraphState(TypedDict):
    """
    LangGraph state schema for the artifact validation loop.
    """
    artifacts: List[Artifact]
    validation_errors: List[str]


def verify_python_code(content: str) -> Optional[str]:
    """
    Verifies Python code using the built-in AST parser.
    Returns an error string if invalid, None if valid.
    """
    try:
        ast.parse(content)
        return None
    except SyntaxError as e:
        return f"Python SyntaxError: {e}"
    except Exception as e:
        return f"Unexpected error during Python validation: {e}"


def verify_typescript_code(content: str) -> Optional[str]:
    """
    Verifies TypeScript/JavaScript code by shelling out to node --check.
    Returns an error string if invalid, None if valid.
    """
    try:
        with tempfile.NamedTemporaryFile(suffix=".js", delete=False) as tmp:
            tmp.write(content.encode('utf-8'))
            tmp_path = tmp.name

        # We use node --check for a fast, pragmatic syntax validation.
        # In a heavier setup, this could be `tsc --noEmit`.
        result = subprocess.run(
            ["node", "--check", tmp_path],
            capture_output=True,
            text=True
        )
        os.remove(tmp_path)
        
        if result.returncode != 0:
            return f"TypeScript/JS SyntaxError: {result.stderr.strip()}"
        return None
    except FileNotFoundError:
        return "Validation Error: Node.js is not installed or not in PATH."
    except Exception as e:
        return f"Execution error during TS validation: {e}"


def artifact_verification_node(state: GraphState) -> GraphState:
    """
    LangGraph node that acts as a verification gate.
    Mutates the state's observations and populates validation_errors.
    """
    errors = []
    
    for artifact in state["artifacts"]:
        err = None
        
        if artifact.language.lower() == "python":
            err = verify_python_code(artifact.content)
        elif artifact.language.lower() in ["typescript", "ts", "javascript", "js"]:
            err = verify_typescript_code(artifact.content)
        else:
            err = f"Unsupported language for verification: {artifact.language}"

        # STD-AUD-1: Record the observation cleanly, separate from claims.
        if err:
            errors.append(f"Artifact {artifact.id}: {err}")
            artifact.observations["syntax_valid"] = False
            artifact.observations["syntax_error"] = err
        else:
            artifact.observations["syntax_valid"] = True
            artifact.observations.pop("syntax_error", None)

    return {
        "artifacts": state["artifacts"],
        "validation_errors": errors
    }
