import datetime
from sqlalchemy import Column, Integer, String, Float, DateTime, JSON, MetaData
from sqlalchemy.orm import declarative_base

# Define naming convention for constraints to ensure reliable migrations
convention = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s"
}
metadata = MetaData(naming_convention=convention)
Base = declarative_base(metadata=metadata)

class AIAuditLog(Base):
    """
    Audit log for AI agent execution and verification.
    Provides audit-proof records for code generated by autonomous agents.
    """
    __tablename__ = 'ai_audit_logs'

    id = Column(Integer, primary_key=True, autoincrement=True)
    execution_id = Column(String(255), nullable=False, index=True)
    timestamp = Column(DateTime(timezone=True), default=datetime.datetime.utcnow, nullable=False)
    
    # STD-AUD-1: Claims and observations never share a field
    agent_claims = Column(JSON, default=dict, nullable=False, 
                         comment="Claims: What the agent says it did (e.g., files written, tests run)")
    system_observations = Column(JSON, default=dict, nullable=False, 
                                comment="Observations: What the daemon, tests, and checks actually saw")
    
    # Exception and Resilience Tracking (System Observations)
    llm_timeout_duration_ms = Column(Float, default=0.0, nullable=False, 
                                    comment="Total duration of LLM timeouts in milliseconds")
    retry_count = Column(Integer, default=0, nullable=False, 
                        comment="Number of retries attempted due to failures/timeouts")
    self_correction_iterations = Column(Integer, default=0, nullable=False, 
                                       comment="Number of self-correction loops executed by LangGraph")

    def __repr__(self):
        return (f"<AIAuditLog(execution_id='{self.execution_id}', "
                f"retry_count={self.retry_count}, "
                f"self_correction_iterations={self.self_correction_iterations})>")
